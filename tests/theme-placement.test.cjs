const test = require('node:test');
const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const result = buildSync({ entryPoints: ['app/models/theme-placement.server.ts'], bundle: true, platform: 'node', format: 'cjs', write: false });
const mod = { exports: {} };
new Function('module', 'exports', result.outputFiles[0].text)(mod, mod.exports);
const { detectPlacements, themePlacements } = mod.exports;
const block = (app='magicpromo-dev', handle='offer', disabled=false) => ({ type: `shopify://apps/${app}/blocks/${handle}/extension-id`, disabled });
const file = (filename, value) => ({ filename, body: { content: '/* Generated by Shopify */\n' + JSON.stringify(value) } });
const settings = (blocks={}) => file('config/settings_data.json', { current: { blocks } });
const template = (name, blocks, disabled=false) => file(`templates/${name}.json`, { sections: { main: { blocks, disabled } }, order: ['main'] });
test('saved cart block and enabled embed are detected independently of product', () => {
  const status = detectPlacements([settings({ a: block('magicpromo-dev','announcement') }), template('cart', { a: block() })], 'magicpromo-dev');
  assert.equal(status.announcement.state, 'added');
  assert.equal(status.cart.state, 'added');
  assert.equal(status.cart.template, 'cart');
  assert.equal(status.product.state, 'missing');
});
test('production app blocks do not complete dev setup', () => {
  const status = detectPlacements([settings({ a: block('magicpromo','announcement') }), template('cart', { a: block('magicpromo') })], 'magicpromo-dev');
  assert.equal(status.announcement.state, 'missing');
  assert.equal(status.cart.state, 'missing');
});
test('disabled embeds, blocks and sections are not marked added; alternate templates work', () => {
  const status = detectPlacements([settings({ a: block('magicpromo-dev','announcement',true) }), template('cart', { a: block() }, true), template('product.special', { a: block() })], 'magicpromo-dev');
  assert.equal(status.announcement.state, 'disabled');
  assert.equal(status.cart.state, 'disabled');
  assert.deepEqual(status.product, { state: 'added', template: 'product.special' });
});
test('enabled occurrence wins and blocks omitted from order do not count', () => {
  const t = template('cart', { a: block() });
  const json = JSON.parse(t.body.content.split('\n')[1]);
  json.sections.main.block_order = [];
  assert.equal(detectPlacements([settings(), file('templates/cart.json',json)], 'magicpromo-dev').cart.state,'missing');
  const status = detectPlacements([settings(), template('product', { a: block() }), template('product.special',{ a: block() },true)],'magicpromo-dev');
  assert.equal(status.product.state,'added');
});
test('unreadable configuration reports unknown without corrupting other placements', () => {
  const status = detectPlacements([{ filename:'config/settings_data.json', body:{content:'invalid'} }, template('cart',{a:block()})], 'magicpromo-dev');
  assert.equal(status.announcement.state,'unknown');
  assert.equal(status.cart.state,'added');
});
test('theme reads paginate and use authenticated app identity', async () => {
  let calls=0;
  const status = await themePlacements(async (_, {variables}) => {
    assert.equal(variables.id,'gid://shopify/OnlineStoreTheme/123');
    assert.equal(variables.after,calls===0?null:'next');
    return Response.json({ data:{ currentAppInstallation:{app:{handle:'magicpromo-dev'}}, theme:{files:{nodes:calls++===0?[settings()]:[template('cart',{a:block()})],pageInfo:{hasNextPage:calls===1,endCursor:'next'}}}} });
  }, '123');
  assert.equal(calls,2);
  assert.equal(status.cart.state,'added');
});
test('API failures and missing app identity never become missing placements', async () => {
  await assert.rejects(themePlacements(async()=>Response.json({errors:[{message:'Denied'}]}),'123'));
  await assert.rejects(themePlacements(async()=>Response.json({data:{theme:{files:{nodes:[]}}}}),'123'));
  await assert.rejects(themePlacements(async()=>{throw new Error('must not call');},'../123'));
});

test('an empty Apps section in the cart template is offered for reuse', () => {
  const cart = (sections, order) => file('templates/cart.json', { sections, order });
  const empty = detectPlacements([settings(), cart({ main: { type: 'main-cart' }, leftover: { type: 'apps', blocks: {} } }, ['main', 'leftover'])], 'magicpromo-dev');
  assert.deepEqual(empty.cart, { state: 'missing', emptyAppsSectionId: 'leftover' });
  const occupied = detectPlacements([settings(), cart({ other: { type: 'apps', blocks: { x: block('other-app') } } }, ['other'])], 'magicpromo-dev');
  assert.equal(occupied.cart.emptyAppsSectionId, undefined);
  const added = detectPlacements([settings(), cart({ ours: { type: 'apps', blocks: { a: block() } }, spare: { type: 'apps' } }, ['ours', 'spare'])], 'magicpromo-dev');
  assert.deepEqual(added.cart, { state: 'added', template: 'cart' });
});
